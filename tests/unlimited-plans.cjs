'use strict';
const assert=require('node:assert/strict'),E=require('../engine.js');
const s=E.lobby(98337),id=E.addPlayer(s,'Player');E.start(s,0);
s.tiles.fill(1);E.person(s,id).troops=1000;
const first=Array.from({length:4200},(_,k)=>3000+k);
const second=Array.from({length:4600},(_,k)=>6000+k);
const order=(cells)=>E.action(s,id,{type:'send',x:1,y:1,zone:cells,targets:[0],percent:25});
const initial=order(first);assert(initial.ok,initial.error);
const union=order(second);assert(union.ok,union.error);
const merged=new Set([...first,...second]);assert.equal(merged.size,7600);
assert.equal(s.attackPlans.length,1,'Overlapping plans must merge without refusing');
assert.equal(s.attackPlans[0].zoneCells.length,merged.size,'All marked cells must survive merge');
const plan=s.attackPlans[0];
const trimmed=E.action(s,id,{type:'erasePlanCells',cells:plan.zoneCells.slice(0,4100)});
assert(trimmed.ok,trimmed.error);
assert.equal(trimmed.erased,4100);
assert.equal(plan.zoneCells.length,3500);
assert.equal(E.BUILD,'v68','Build marker reveals outdated game engine');
console.log('PASS: 4,200 + 4,600 cells merge into a 7,600-cell plan; 4,100-cell eraser works');
